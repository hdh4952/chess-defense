/**
 * 기물 옆면 프로파일 — LatheGeometry로 Y축을 돌려 3D 형상을 만든다 (v1.21).
 *
 * ★ **왜 선반(lathe)인가.** 실제 체스말은 나이트를 뺀 전부가 목선반으로 깎은 회전체다.
 * 그래서 옆면 윤곽선 하나만 있으면 진짜 체스말 형상이 그대로 나온다 — 외부 3D 에셋도,
 * 번들 증가도, 라이선스 문서화도 필요 없고, 티어별 크기·색은 숫자 몇 개로 조정된다.
 * 나이트만 회전체가 아니라 예외이며, 머리는 geometry.ts가 압출(extrude)로 따로 만든다.
 *
 * 각 점은 `[반지름, 높이]`다. **첫 점과 마지막 점의 반지름은 반드시 0**이어야 한다 —
 * lathe는 윤곽선을 회전시킬 뿐 뚜껑을 덮어 주지 않으므로, 양 끝이 축에 닿지 않으면 바닥과
 * 꼭대기가 뚫린 껍데기가 되어 안쪽 면이 비쳐 보인다.
 *
 * 높이 단위는 보드 픽셀과 같다(coords.ts) — 칸이 80px이므로 폰 46은 칸 높이의 약 0.58이다.
 */
export type Profile = readonly (readonly [number, number])[];

/**
 * ★ **v1.23에서 전 기물의 비율을 치비(디포르메)로 다시 잡았다** — 스타일라이즈드 전환의
 * 셋째 축이다(툰 셰이딩 · 윤곽선 · **비율**).
 *
 * 규칙은 캐주얼 아트의 관습 그대로다: **받침을 굵게, 키를 낮게, 머리를 크게.** 실제 체스말
 * 비율은 "정교한 물건"으로 읽히고, 굵고 낮고 머리 큰 비율은 "캐릭터"로 읽힌다. 대략
 * 받침 반지름 +25% · 전체 높이 −10% · 머리 반지름 +30%다.
 *
 * ★ **형상이 데이터 테이블이라 이 변경이 이 파일 하나로 끝났다.** 지오메트리 코드도,
 * 렌더러도, 좌표 계산도 한 줄 바뀌지 않았다 — 절차적 생성을 고른 값이 여기서 회수된다.
 */

