/**
 * 감속 표식의 잉크 — **세 모듈이 이 파일 하나를 공유한다.**
 *
 * renderer.ts(칸 꺾쇠 · 적 고리) · highlights.ts(칸 채우기) · effects.ts("−30%" 라벨)가
 * 각자 다른 알파로 같은 색을 쓴다. 완성된 색 문자열은 알파가 달라 공유할 수 없으므로 RGB
 * 성분만 문자열로 두고 각자 알파를 붙인다. 세 파일에 각각 적어 두면 톤을 조정할 때 반드시
 * 한 곳이 옛 색으로 남고, 그 어긋남은 "같은 능력인데 색이 다르다"로 화면에 나타난다.
 *
 * 이 파일이 따로 있는 이유는 의존 방향이다. effects.ts와 highlights.ts는 renderer.ts를
 * 모르고(반대 방향으로만 안다), renderer.ts에 상수를 두면 그 방향이 뒤집힌다. 값만 있는
 * 잎 모듈로 빼면 셋 다 아래로만 의존한다.
 *
 * ★ 청록(#4FD1C5) 계열을 피한 것이 결정적이다 — 그건 swift(빠른 적) 유형의 색이라 감속에
 * 쓰면 뜻이 정확히 반대로 겹친다. 퀸 라인(#009FD9)보다 훨씬 밝고 채도가 낮은 얼음색이라
 * 같은 파랑 계열 안에서도 명도로 갈린다. 색조가 아니라 **명도 + 형태**로 자기를 구분한다.
 */
